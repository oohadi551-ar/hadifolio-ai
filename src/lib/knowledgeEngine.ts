      const sources = matchedUnits.map(u => ({
        materialTitle: u.sourceTitle,
        snippet: u.fullHeading + ' - ' + (u.content.slice(0, 150).replace(/[#*]/g, '') + '...'),
      }));

      const followUps = matchedUnits.map(u => `اشرح لي بالتفصيل ما ورد في الوحدة ${u.unitArabic}`);
      if (followUps.length < 3) {
        followUps.push('اختبرني بأسئلة اختيار من متعدد حول هذه الوحدات');
      }

